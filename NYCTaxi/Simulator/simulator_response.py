import pandas as pd
import numpy as np
import joblib # For loading the scaler
import json   # For loading the list of scaled features
from pathlib import Path
import os

def _resolve_scenario_dir(scenario_name=None, base_dir=None):
    """
    Resolve directory that contains beta_simulator artifacts.
    Priority:
    1) explicit `base_dir`
    2) env `BETA_SIMULATOR_DIR`
    3) current file directory
    If `scenario_name` is provided, append it as a subfolder.
    """
    if base_dir:
        root = Path(base_dir)
    elif os.getenv("BETA_SIMULATOR_DIR"):
        root = Path(os.getenv("BETA_SIMULATOR_DIR"))
    else:
        root = Path(__file__).resolve().parent

    return root / scenario_name if scenario_name else root


def load_beta_simulator(scenario_name=None, base_dir=None):
    """
    Loads Beta_simulator parameters from the saved CSV file.
    Returns a dictionary with 'intercept' and 'coefficients' (as a pandas Series).
    """
    try:
        scenario_dir = _resolve_scenario_dir(scenario_name=scenario_name, base_dir=base_dir)
        df_betas = pd.read_csv(scenario_dir / "beta_simulator_parameters.csv")
        intercept = df_betas[df_betas['feature'] == 'intercept']['coefficient'].iloc[0]
        coeffs_df = df_betas[df_betas['feature'] != 'intercept']
        coefficients = pd.Series(coeffs_df['coefficient'].values, index=coeffs_df['feature'].values)
        print("Beta_simulator parameters loaded successfully.")
        return {'intercept': intercept, 'coefficients': coefficients}
    except Exception as e:
        print(f"Error loading beta_simulator_parameters.csv: {e}")
        print("Ensure the file exists and is correctly formatted.")
        return None

def load_scaler_and_features(scenario_name=None, base_dir=None):
    """
    Loads the saved StandardScaler object and the list of features that were scaled.
    """
    try:
        scenario_dir = _resolve_scenario_dir(scenario_name=scenario_name, base_dir=base_dir)
        scaler_path = scenario_dir / "beta_simulator_scaler.joblib"
        if scaler_path.exists():
            scaler = joblib.load(scaler_path)
        else:
            scaler = None

        with open(scenario_dir / "beta_simulator_scaled_features_list.json", 'r') as f:
            scaled_feature_names = json.load(f)
        print("StandardScaler and scaled features list loaded successfully.")
        return scaler, scaled_feature_names
    except Exception as e:
        print(f"Error loading scaler or scaled_features_list.json: {e}")
        print("Ensure these files were generated by the beta_simulator_estimation script.")
        return None, None

def simulate_passenger_acceptance(price_offered, trip_features_dict, 
                                  beta_simulator, scaler, scaled_feature_names_list):
    """
    Simulates whether a passenger accepts an offered price based on a logistic demand model.

    Args:
        price_offered (float): The price offered by your pricing algorithm.
        trip_features_dict (dict): A dictionary of contextual features for the current trip.
                                   Example: {'distance_km': 5.0, 'pickup_hour_of_day': 10, ...}
        beta_simulator (dict): Dictionary containing 'intercept' and 'coefficients' (a pandas Series
                               with feature names as index) for the demand model.
        scaler (sklearn.preprocessing.StandardScaler): The fitted scaler object used when training beta_simulator.
        scaled_feature_names_list (list): List of feature names that were scaled during beta_simulator training.
                                         The order must match the scaler's expectations.

    Returns:
        int: 1 if the offer is accepted, 0 if rejected.
             Returns -1 if inputs are invalid or an error occurs.
    """
    if beta_simulator is None or scaler is None or scaled_feature_names_list is None:
        print("Error: beta_simulator, scaler, or scaled_feature_names_list is not properly loaded.")
        return -1 # Indicate an error

    intercept = beta_simulator['intercept']
    coefficients = beta_simulator['coefficients'] # This is a pandas Series

    # Prepare the feature vector for the model in the correct order
    # The order of features in 'coefficients.index' is the one the model expects
    model_feature_order = coefficients.index.tolist()
    
    # Create a Series for the current instance with all expected model features.
    # Supports both legacy format (price main effect) and interaction format (price_x_*).
    instance_series = pd.Series(index=model_feature_order, dtype=float)
    if "price_offered" in instance_series.index:
        instance_series["price_offered"] = price_offered

    for feature_name in model_feature_order:
        if feature_name.startswith("price_x_"):
            base_feat = feature_name[len("price_x_"):]
            base_val = trip_features_dict.get(base_feat, 0)
            instance_series[feature_name] = price_offered * base_val
        elif feature_name != "price_offered":
            instance_series[feature_name] = trip_features_dict.get(feature_name, 0)

    instance_series.fillna(0, inplace=True)


    # 2. Scale the numerical features that were scaled during training
    # Create a DataFrame from the instance_series for the scaler
    instance_df_for_scaling = pd.DataFrame([instance_series]) # Scaler expects DataFrame
    
    # Ensure only columns that were originally scaled are attempted to be transformed
    cols_to_scale_for_this_instance = [col for col in scaled_feature_names_list if col in instance_df_for_scaling.columns]

    if scaler is not None and cols_to_scale_for_this_instance:
        try:
            instance_df_for_scaling[cols_to_scale_for_this_instance] = scaler.transform(instance_df_for_scaling[cols_to_scale_for_this_instance])
        except ValueError as ve:
            print(f"ValueError during scaling: {ve}. This might be due to new feature values scaler hasn't seen (e.g. for OHE'd features if scaler included them).")
            print("Ensure the scaler was fit only on truly numerical continuous features.")
            return -1
        except Exception as e:
            print(f"Error during scaling: {e}")
            return -1


    # 3. Reconstruct the scaled feature vector in the correct order of model coefficients
    # X_scaled_instance_values should align with coefficients.index
    X_scaled_instance_values = instance_df_for_scaling.iloc[0][coefficients.index]


    # 4. Calculate Z
    # Ensure alignment between X_scaled_instance_values and coefficients
    if not X_scaled_instance_values.index.equals(coefficients.index):
        print("Error: Feature order mismatch between input instance and model coefficients after scaling.")
        # Attempt reordering if possible, or fail
        try:
            X_scaled_instance_values = X_scaled_instance_values.reindex(coefficients.index).fillna(0) # Fill any new NaNs with 0
            print("Attempted to reindex X_scaled_instance_values. Check for NaNs if this was unexpected.")
        except Exception as e_reindex:
            print(f"Failed to reindex: {e_reindex}")
            return -1


    Z = intercept + np.dot(X_scaled_instance_values.values, coefficients.values)

    # 5. Calculate probability of acceptance
    p_accept = 1 / (1 + np.exp(-Z))

    # 6. Simulate acceptance based on probability
    if np.random.rand() <= p_accept:
        return 1 # Accepted
    else:
        return 0 # Rejected

